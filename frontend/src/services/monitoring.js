import api from './api'

export const getHosts = () => api.get('/monitoring/hosts')
export const getProblems = () => api.get('/monitoring/problems')
export const getHistory = (hours = 24) => api.get(`/monitoring/history?hours=${hours}`)
export const getHostMetrics = (hostId, hours = 2) => api.get(`/monitoring/hosts/${hostId}/metrics`, { params: { hours } })
export const getUnifiApPanel = () => api.get('/monitoring/unifi-aps')
export const getUnifiApHistory = (apName, hours = 24) => api.get('/monitoring/unifi-aps/history', { params: { apName, hours } })
export const getUnifiApInstability = () => api.get('/monitoring/unifi-aps/instability')
export const createUnifiApInvestigationTicket = (apName, reason) => api.post('/monitoring/unifi-aps/instability/tickets', { apName, reason })
export const getIncidents = (params = {}) => api.get('/incidents', { params })
export const getIncidentSummary = () => api.get('/incidents/summary')
export const closeIncident = (incidentId, reason) => api.post(`/incidents/${incidentId}/close`, { reason })
export const reopenIncident = (incidentId, reason) => api.post(`/incidents/${incidentId}/reopen`, { reason })
export const getIncidentAnalysis = (incidentId) => api.get(`/incidents/${incidentId}/analysis`)
export const getIncidentAutoResolution = (incidentId) => api.get(`/incidents/${incidentId}/auto-resolution`)
export const checkIncidentAutoResolution = (incidentId) => api.post(`/incidents/${incidentId}/auto-resolve-check`)
export const checkAllIncidentAutoResolution = () => api.post('/incidents/auto-resolve-check')
export const getIncidentRunbook = (incidentId) => api.get(`/incidents/${incidentId}/runbook`)
export const executeIncidentAction = (incidentId, actionKey) => api.post(`/incidents/${incidentId}/actions/${actionKey}`)
export const createIncidentTicket = (incidentId, reason) => api.post(`/incidents/${incidentId}/tickets`, { reason })
export const getAlertTriage = (includeSuppressed = true) => api.get('/monitoring/triage', { params: { includeSuppressed } })
export const decideAlert = (payload) => api.post('/monitoring/triage/decisions', payload)
export const createAlertTicket = (eventId) => api.post('/monitoring/triage/tickets', { eventId })
export const createAlertRule = (payload) => api.post('/monitoring/triage/rules', payload)
export const updateAlertRuleEnabled = (id, enabled) => api.put(`/monitoring/triage/rules/${id}/enabled`, { enabled })
